#include "libft.h"
//#include <stdio.h>

int	ft_atoi(const char *str)
{
	int	num;
	int	negative;

	num = 0;
	negative = 1;
	while (*str == 32 || (*str >= 9 && *str <= 13))
	{
		str++;
	}
	if (*str == '-' || *str == '+')
	{
		if (*str == '-')
			negative = -1;
		str++;
	}
	while (*str >= '0' && *str <= '9')
	{
		num = num * 10 + (*str - '0');
		str++;
	}
	return (num * negative);
}

